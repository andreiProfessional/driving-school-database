CREATE TABLE CATEGORIE_PERMIS (
    ID_CATEGORIE_PERMIS NUMBER PRIMARY KEY,
    COD VARCHAR2(3) NOT NULL UNIQUE,
    VARSTA_MINIMA NUMBER NOT NULL CHECK (VARSTA_MINIMA >= 0),
    MINIM_ORE_PREGATIRE NUMBER NOT NULL CHECK (MINIM_ORE_PREGATIRE >= 0)
);

CREATE TABLE CURS (
    ID_CURS NUMBER PRIMARY KEY,
    DENUMIRE VARCHAR2(100) NOT NULL,
    ORE_PREGATIRE NUMBER NOT NULL CHECK (ORE_PREGATIRE >= 0),
    ID_CATEGORIE_PERMIS NUMBER NOT NULL,
    CONSTRAINT FK_CURS_CATEGORIE_PERMIS FOREIGN KEY (ID_CATEGORIE_PERMIS) REFERENCES CATEGORIE_PERMIS(ID_CATEGORIE_PERMIS)
);

CREATE TABLE ELEV (
    ID_ELEV NUMBER PRIMARY KEY,
    CNP CHAR(13) NOT NULL UNIQUE CHECK (LENGTH(CNP) = 13),
    NUME VARCHAR2(100) NOT NULL,
    TELEFON VARCHAR2(15),
    EMAIL VARCHAR2(255)
);

CREATE TABLE CONTRACT (
    ID_CONTRACT NUMBER PRIMARY KEY,
    DATA_INCEPUT DATE NOT NULL,
    DATA_FINAL DATE NOT NULL,
    CONSTRAINT CHECK_DATA_INCEPUT_FINAL CHECK (DATA_INCEPUT <= DATA_FINAL),
    TAXA NUMBER NOT NULL CHECK (TAXA >= 0),
    ID_CURS NUMBER NOT NULL,
    CONSTRAINT FK_CONTRACT_CURS FOREIGN KEY (ID_CURS) REFERENCES CURS(ID_CURS),
    ID_ELEV NUMBER NOT NULL,
    CONSTRAINT FK_CONTRACT_ELEV FOREIGN KEY (ID_ELEV) REFERENCES ELEV(ID_ELEV)
);

CREATE TABLE AUTOVEHICUL (
    ID_AUTOVEHICUL NUMBER PRIMARY KEY,
    NUMAR_INMATRICULARE VARCHAR2(8) NOT NULL UNIQUE,
    MARCA VARCHAR2(50) NOT NULL,
    MODEL VARCHAR2(50) NOT NULL,
    AN_FABRICATIE NUMBER NOT NULL CHECK (AN_FABRICATIE >= 1886),
    ID_CATEGORIE_PERMIS NUMBER NOT NULL,
    CONSTRAINT FK_AUTOVEHICUL_CATEGORIE_PERMIS FOREIGN KEY (ID_CATEGORIE_PERMIS) REFERENCES CATEGORIE_PERMIS(ID_CATEGORIE_PERMIS)
);

CREATE TABLE INSTRUCTOR (
    ID_INSTRUCTOR NUMBER PRIMARY KEY,
    NUME VARCHAR2(100) NOT NULL,
    DATA_ANGAJARII DATE,
    SALARIU NUMBER NOT NULL CHECK (SALARIU >= 0),
    TELEFON VARCHAR2(15),
    EMAIL VARCHAR2(255)
);

CREATE TABLE SEDINTA (
    ID_SEDINTA NUMBER PRIMARY KEY,
    ORA_INCEPUT DATE NOT NULL,
    ORA_FINAL DATE NOT NULL,
    CONSTRAINT CHECK_ORA_INCEPUT_FINAL CHECK (ORA_INCEPUT <= ORA_FINAL),
    ID_INSTRUCTOR NUMBER NOT NULL,
    CONSTRAINT FK_SEDINTA_INSTRUCTOR FOREIGN KEY (ID_INSTRUCTOR) REFERENCES INSTRUCTOR(ID_INSTRUCTOR),
    ID_AUTOVEHICUL NUMBER NOT NULL,
    CONSTRAINT FK_SEDINTA_AUTOVEHICUL FOREIGN KEY (ID_AUTOVEHICUL) REFERENCES AUTOVEHICUL(ID_AUTOVEHICUL),
    ID_CONTRACT NUMBER NOT NULL,
    CONSTRAINT FK_SEDINTA_CONTRACT FOREIGN KEY (ID_CONTRACT) REFERENCES CONTRACT(ID_CONTRACT)
);

CREATE TABLE CATEGORIE_PERMIS_INSTRUCTOR (
    ID_CATEGORIE_PERMIS NUMBER NOT NULL,
    CONSTRAINT FK_CPI_CATEGORIE_PERMIS FOREIGN KEY (ID_CATEGORIE_PERMIS) REFERENCES CATEGORIE_PERMIS(ID_CATEGORIE_PERMIS),
    ID_INSTRUCTOR NUMBER NOT NULL,
    CONSTRAINT FK_CPI_INSTRUCTOR FOREIGN KEY (ID_INSTRUCTOR) REFERENCES INSTRUCTOR(ID_INSTRUCTOR),
    CONSTRAINT PK_CATEGORIE_PERMIS_INSTRUCTOR PRIMARY KEY (ID_CATEGORIE_PERMIS, ID_INSTRUCTOR)
);
